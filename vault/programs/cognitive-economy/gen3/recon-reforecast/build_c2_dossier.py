"""Zero-model dossier for the C2a lease (CP50 run plan C2, first deliverable: the arm-A executor; nothing sent).

Run: python vault/programs/cognitive-economy/gen3/recon-reforecast/build_c2_dossier.py
Writes C2A-DOSSIER.md next to this file: module docstrings (the CLI contracts) and verbatim AST extracts, with line
numbers, of the arm-A candidate path -- bench.py (the executor seam), baseline.arms_block, m2c_producer, gex44
candidate.py / candidate_ledger.py / capsule_build.py / stage.py / runner_lib.mode_candidate / repatriate.py /
custody.py -- plus ROADMAP Phase 7, REFORECAST section 3, the C1 receipt, the per-cohort packet template, the live RF
job cap and the jobs already counted against Phase 7. Any piece the extractor cannot find is printed as UNKNOWN.
Code is read from the C2 work tree (wt_cp50_c2); data inputs stay absolute under wt_keosdtk_home, as in C1.
"""
import ast
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from build_c1_dossier import extract, ids_sha, read_lines, section, sha, top_names  # noqa: E402

WT = r"C:\Users\User\Apps\recon_work\wt_cp50_c2"
DATA_WT = r"C:\Users\User\Apps\recon_work\wt_keosdtk_home"
DEC = os.path.join(WT, "tools", "wros", "binary", "decomp")
G = os.path.join(DEC, "gex44")
RF = os.path.join(WT, ".planning", "workstreams", "recon-factory")
FREEZE = os.path.join(DATA_WT, ".planning", "workstreams", "recon-factory", "phases", "07-g0-freeze", "G0_FREEZE.json")
GEN3 = os.path.dirname(HERE)
REFORECAST = os.path.join(HERE, "REFORECAST.md")
C1_RECEIPT = os.path.join(GEN3, "C1-receipt.md")
TEMPLATE = os.path.join(GEN3, "packets", "C2-cohort-TEMPLATE.md")
OUT = os.path.join(HERE, "C2A-DOSSIER.md")
ANCHOR_DRAW = "0f2ecb37"

# file -> (full-body names, signature-only names); "*" = every top-level def, "<consts>" = assignments before the 1st def.
SPEC = {
    os.path.join(DEC, "bench.py"): (["<consts>", "load_draw", "cohorts", "validate_record", "run_cohort"], ["*"]),
    os.path.join(DEC, "baseline.py"): (["arms_block"], ["load_inputs", "stratum_of"]),
    os.path.join(DEC, "m2c_producer.py"): (["admit", "main"], ["*"]),
    os.path.join(G, "candidate.py"): (["load_units", "build_units", "classify_unit", "judge_tree", "cmd_judge"], ["*"]),
    os.path.join(G, "candidate_ledger.py"): ([], ["*"]),
    os.path.join(G, "capsule_build.py"): (["default_inputs", "resolve_units", "resolve_targets", "build"],
                                          ["_stage_and_seal", "verify_current", "main"]),
    os.path.join(G, "stage.py"): (["job_params", "build", "send", "wait"], ["*"]),
    os.path.join(G, "runner_lib.py"): (["_check_candidate_unit", "mode_candidate"], []),
    os.path.join(G, "repatriate.py"): ([], ["verify_tree", "ingest", "fetch", "main"]),
    os.path.join(G, "custody.py"): ([], ["validate_capsule_manifest", "current_capsule", "judge_receipt", "cmd_judge"]),
}
DOCSTRINGS = ["bench.py", "m2c_producer.py", "candidate.py", "candidate_ledger.py", "capsule_build.py", "stage.py",
              "repatriate.py"]


def module_doc(path):
    return ast.get_docstring(ast.parse(open(path, encoding="utf-8").read())) or "UNKNOWN (no module docstring)"


def rf_phase7_state():
    """Live RF cap and current phase from stage.py, and the jobs-ledger rows already counted against phase 7."""
    src = open(os.path.join(G, "stage.py"), encoding="utf-8").read()
    _, consts = top_names(ast.parse(src))
    lines = src.splitlines()
    out = []
    for name in ("RF_GEX44_ROOT", "RF_PHASE_JOB_CAPS", "RF_CURRENT_PHASE", "CANDIDATE_BUDGET_S", "CAPSULE_MODES"):
        n = consts.get(name)
        out.append("- `%s`" % " ".join(l.strip() for l in lines[n.lineno - 1:n.end_lineno]) if n
                   else "- `%s`: UNKNOWN" % name)
    root = r"C:\Users\User\Apps\recon_work\recon_factory\gex44"
    ledger = os.path.join(root, "jobs_ledger.jsonl")
    if os.path.isfile(ledger):
        rows = [json.loads(l) for l in open(ledger, encoding="utf-8") if l.strip()]
        by = {}
        for r in rows:
            by[r.get("phase", 1)] = by.get(r.get("phase", 1), 0) + 1
        out.append("- RF jobs ledger `%s`: rows=%d per phase %s (phase 7 used = %d of its cap)" % (
            ledger, len(rows), json.dumps(by, sort_keys=True), by.get(7, 0)))
    else:
        out.append("- RF jobs ledger: UNKNOWN (no %s)" % ledger)
    return out


def main():
    unknown = []
    body = ["# C2a dossier (zero-model, generated by build_c2_dossier.py)", "",
            "Everything below is copied or computed from a named source. Read this file only. UNKNOWN = not found on"
            " disk by the extractor; never fill it in by guessing.", "", "## Inputs (sha256)"]
    roadmap_p = os.path.join(RF, "ROADMAP.md")
    for p in list(SPEC) + [FREEZE, roadmap_p, REFORECAST, C1_RECEIPT, TEMPLATE]:
        if os.path.isfile(p):
            body.append("- `%s` sha256 `%s`" % (p, sha(p)))
        else:
            body.append("- `%s` UNKNOWN (missing)" % p)
            unknown.append(p)

    body += ["", "## Measured facts (this run)"]
    if os.path.isfile(FREEZE):
        sys.path.insert(0, DEC)
        import bench  # noqa: E402  (stdlib-only by GAP-3; load_draw recomputes the anchor itself)
        entries = bench.load_draw(FREEZE)
        first5 = entries[:5]
        body.append("- bench.load_draw(G0_FREEZE.json): n=%d, sorted-id sha256 %s (anchor %s %s)" % (
            len(entries), ids_sha([e["census_id"] for e in entries]), ANCHOR_DRAW,
            "MATCH" if ids_sha([e["census_id"] for e in entries]).startswith(ANCHOR_DRAW) else "no match"))
        body.append("- pilot cohort = draw positions 1-5 (plan C2), entries verbatim:")
        body += ["  - `%s`" % json.dumps(e, sort_keys=True) for e in first5]
    body += rf_phase7_state()

    for name, p, start, stop in (
            ("ROADMAP Phase 7 (verbatim)", roadmap_p, lambda l: l.startswith("### Phase 7:"),
             lambda l: l.startswith("### Phase ") or l.startswith("## ")),
            ("REFORECAST section 3 (verbatim; amendment (d) = the record fields)", REFORECAST,
             lambda l: l.startswith("## 3."), lambda l: l.startswith("## "))):
        sec = section(read_lines(p), start, stop) if os.path.isfile(p) else None
        body += ["", "## " + name] + (sec or ["UNKNOWN"])
        if sec is None:
            unknown.append(name)
    for name, p in (("C1 receipt (verbatim)", C1_RECEIPT), ("Per-cohort packet template (verbatim)", TEMPLATE)):
        body += ["", "## " + name] + (read_lines(p) if os.path.isfile(p) else ["UNKNOWN"])

    body += ["", "## Module docstrings (CLI contracts, verbatim)"]
    for base in DOCSTRINGS:
        p = next((q for q in SPEC if os.path.basename(q) == base), None)
        body += ["", "### %s" % base, "```"] + (module_doc(p).splitlines() if p and os.path.isfile(p) else ["UNKNOWN"]) \
            + ["```"]

    missing_all = []
    for path, (full, sigs) in SPEC.items():
        if not os.path.isfile(path):
            body += ["", "## %s: UNKNOWN (file missing)" % os.path.relpath(path, WT)]
            missing_all.append(os.path.basename(path))
            continue
        part, missing = extract(path, full, sigs)
        missing_all += ["%s:%s" % (os.path.basename(path), m) for m in missing]
        body += ["", "## %s (verbatim extracts)" % os.path.relpath(path, WT)] + part
    body += ["", "Not found by the extractor (UNKNOWN): %s" % ((missing_all + unknown) or "none")]

    text = "\n".join(body) + "\n"
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("C2A-DOSSIER chars=%d est_tokens=%d unknown=%s" % (len(text), len(text) // 4, missing_all + unknown))
    return 0 if not (missing_all or unknown) else 1


if __name__ == "__main__":
    sys.exit(main())
