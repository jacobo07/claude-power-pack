#!/usr/bin/env node
'use strict';
/**
 * session-title-lib.js — readable /resume titles for the LIVE forward path.
 *
 * The native /resume picker renders the LATEST `{"type":"custom-title", ...}`
 * record in `<uuid>.jsonl`; an un-titled session falls back to the 8-char UUID
 * hash. hooks/mark-live-session.js is the only per-turn writer of custom-title;
 * every title decision it makes comes from decideTitle() below, so the hook and
 * tools/test_session_naming.js exercise the same code.
 *
 * Name source, in order (PR-TRANSCRIPT-RENAME-SAFETY-001):
 *   1. the session's own Claude-generated ai-title ({"type":"ai-title"}),
 *   2. the first REAL user prompt (command wrappers, caveats, skill bodies and
 *      tool results skipped; a slash command's args count as the prompt),
 *   3. the 8-char hash, last resort.
 *
 * DEFERRAL (measured 2026-10-06): the harness only generates an ai-title for a
 * session that has NO custom-title yet. Of 1,306 recent transcripts whose first
 * custom-title preceded any ai-title, 1,303 never got one — this hook's early
 * "⚡ <hash>" write was suppressing the very title it waited for. So a session
 * with no custom-title and no ai-title is left untitled for its first
 * DEFER_PROMPTS prompts.
 *
 * Lifecycle markers on top of the base title:
 *   "⚡ <base>"            live in some pane      (Stop / SessionStart)
 *   "<base>"               died without closing   (orphan sweep, SessionEnd other)
 *   "<base> ✓ terminada"   closed on purpose      (SessionEnd clear / exit / logout)
 * A plain title after a reboot is therefore a session to reopen.
 *
 * Pure + dependency-free (fs only). Every function fails soft: any error or
 * missing signal returns null / '' / the hash, never throws.
 */
const fs = require('fs');

const HEAD_BYTES = 512 * 1024;      // bounded head scan (first prompts, early ai-title)
const TAIL_BYTES = 256 * 1024;      // bounded tail scan (latest ai-title / custom-title)
const MAX_LABEL = 60;               // matches rename_sessions.py MAX_LABEL
const MAX_USER_MSGS = 12;           // user records examined for the first real prompt
const DEFER_PROMPTS = 3;            // prompts to wait for the harness ai-title
const LIVE_PREFIX = '⚡ ';           // the mark-live voltage marker
const FINISHED_SUFFIX = ' ✓ terminada';
const HASH_TITLE_RE = /^[0-9a-fA-F]{8}$/;
const FULL_UUID_RE = /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/;
const STUB_COMMANDS = new Set(['clear', 'login', 'logout', 'compact', 'exit', 'quit', 'resume']);

// Text the harness or a skill wraps around a prompt. A title made of it says
// nothing about the session, so it is treated like a hash: replaceable.
const JUNK_TITLE_RE = new RegExp([
  'run directly in Claude Code',
  'generated by the user while running local commands',
  '^Caveat\\s*:',
  '^```',
  '^<',
  '^\\[Request interrupted',
  '^Base directory for this skill',
].join('|'), 'i');

// Lines inside a prompt that are scaffolding, not the topic.
const SKIP_LINE_RE = /^(MODO\s*[:=]|PREFLIGHT\b|EXECUTION\s+MODE\b|ULTRA[- ]?PLAN(\s+MODE)?\b|CONTRATO\s+DE\s+REALIDAD\b|ROI\s*[:=]|CONSTRAINTS?\s*[:=]|DONE[\s-]?GATE\b|Caveat\s*:|Base directory for this skill|Request interrupted|System\s*:|Human\s*:|Assistant\s*:)/i;
const DECOR_RE = /^[\s═─━—–‑\-=_*·•~▪▶►◆●→⇒»«│|<>#/\\.:`]*$/;

// Words that carry no topic: "continue", "go ahead", "sí, hazlo ya". A prompt
// made only of these is a nudge, never a title.
const FILLER_WORDS = new Set((
  'continue continua continúa continuar continuemos sigue seguimos sigamos seguir go ahead on '
  + 'proceed procede adelante dale ok okay vale yes y yeah yep si sí s hazlo hazla do it next '
  + 'retry again keep going carry resume perfecto perfect bien genial great thanks thank you '
  + 'gracias please por favor pls ya then now and e the with that eso esto lo mismo same'
).split(' '));
const DEFAULT_BRANCHES = new Set(['main', 'master', 'head', 'detached', '']);

function words(s) {
  return String(s || '').toLowerCase().replace(/[^\p{L}\p{N}\s]/gu, ' ').split(/\s+/).filter(Boolean);
}

// Only filler words ("go ahead", "sigue"): never a title, stored or derived.
function isFiller(s) {
  const w = words(s);
  return w.length > 0 && w.every(x => FILLER_WORDS.has(x));
}

// A prompt too thin to name a session: filler, or under 3 words that are not a
// slash command ("/cpp-gsd-long unattended" names its session; "y" does not).
function isWeakPrompt(s) {
  const t = String(s || '').trim();
  return isFiller(t) || (!t.startsWith('/') && words(t).length < 3);
}

function isHashTitle(s) {
  const b = (s || '').trim();
  if (!b) return true;
  return HASH_TITLE_RE.test(b) || FULL_UUID_RE.test(b);
}

function isJunkTitle(s) {
  const b = (s || '').trim();
  return isHashTitle(b) || JUNK_TITLE_RE.test(b) || isFiller(b);
}

function hashFallback(sessionId) {
  return sessionId ? String(sessionId).slice(0, 8) : 'session';
}

function readSlice(filePath, fromEnd, maxBytes) {
  try {
    const fd = fs.openSync(filePath, 'r');
    try {
      const size = fs.fstatSync(fd).size;
      const len = Math.min(size, maxBytes);
      if (len <= 0) return '';
      const buf = Buffer.alloc(len);
      fs.readSync(fd, buf, 0, len, fromEnd ? size - len : 0);
      return buf.toString('utf-8');
    } finally { fs.closeSync(fd); }
  } catch { return ''; }
}

function parse(line) {
  try { return JSON.parse(line.trim()); } catch { return null; }
}

// The session's latest Claude-generated ai-title, or '' if none. The harness
// re-emits the record every turn, so the tail normally holds it; the head scan
// covers a session whose tail is one huge tool result.
function readAiTitle(filePath) {
  for (const text of [readSlice(filePath, true, TAIL_BYTES), readSlice(filePath, false, HEAD_BYTES)]) {
    const lines = text.split('\n');
    for (let i = lines.length - 1; i >= 0; i--) {
      if (lines[i].indexOf('"ai-title"') === -1) continue;
      const o = parse(lines[i]);
      // An ai-title made from a fenced prompt is just "```text": not a title.
      if (o && o.type === 'ai-title' && typeof o.aiTitle === 'string' && !isJunkTitle(o.aiTitle)) {
        return o.aiTitle.trim();
      }
    }
  }
  return '';
}

function userText(o) {
  const c = o && o.message && o.message.content;
  if (typeof c === 'string') return c;
  if (Array.isArray(c)) {
    const t = c.find(p => p && p.type === 'text' && typeof p.text === 'string');
    return t ? t.text : '';
  }
  return '';
}

function tagValue(text, tag) {
  const m = new RegExp('<' + tag + '>([\\s\\S]*?)</' + tag + '>', 'i').exec(text);
  return m ? m[1].trim() : '';
}

// First substantive line of a prompt, scaffolding stripped; '' if none.
function cleanPrompt(text) {
  for (const raw of String(text).replace(/<[^>]+>/g, ' ').replace(/\r/g, '').split('\n').slice(0, 60)) {
    const line = raw.trim();
    // A fence marker is skipped, its content is not: some prompts are wholly fenced.
    if (line.startsWith('```') || !line || DECOR_RE.test(line)) continue;
    if (line.startsWith('[') && line.endsWith(']')) continue;
    const s = line.replace(/^[#>*\-\s]+/, '').replace(/\s+/g, ' ').trim();
    if (!s || SKIP_LINE_RE.test(s)) continue;
    // A quoted prompt keeps its words, not its quote marks.
    if ((s.match(/\p{L}/gu) || []).length >= 4) return s.replace(/^["'“”«»]+|["'“”«»]+$/g, '').trim();
  }
  return '';
}

/**
 * Walk the first user records. Returns { title, weak, branch, prompts }:
 * title is the first SUBSTANTIVE prompt ('' if none), weak the first thin one
 * ("continue", "go ahead"), branch the session's git branch when it is not a
 * default one, prompts the count of genuine prompts seen.
 */
function scanPrompts(filePath) {
  let title = '';
  let weak = '';
  let branch = '';
  let launch = null;      // first slash command seen, stub or not
  let prompts = 0;
  let seen = 0;
  for (const line of readSlice(filePath, false, HEAD_BYTES).split('\n')) {
    if (!branch) {
      const mb = /"gitBranch":"([^"]+)"/.exec(line);
      if (mb && !DEFAULT_BRANCHES.has(mb[1].toLowerCase())) branch = mb[1];
    }
    if (line.indexOf('"type":"user"') === -1) continue;
    const o = parse(line);
    if (!o || o.type !== 'user' || o.isMeta) continue;
    if (++seen > MAX_USER_MSGS) break;
    const text = userText(o);
    if (!text.trim()) continue;                                    // tool results
    if (/<(local-command-(caveat|stdout|stderr)|bash-(input|stdout|stderr))>/.test(text)) continue;
    let candidate = '';
    if (text.indexOf('<command-name>') !== -1) {
      const name = tagValue(text, 'command-name').replace(/^\//, '');
      if (launch === null) launch = name.toLowerCase();
      const args = tagValue(text, 'command-args').replace(/^focus on\s+/i, '');
      if (!args || STUB_COMMANDS.has(name.toLowerCase())) continue;
      // One- or two-word args ("unattended") say little alone: keep the command.
      candidate = args.split(/\s+/).length < 3 ? `/${name} ${args}` : args;
    } else {
      candidate = text;
    }
    const cleaned = cleanPrompt(candidate) || (isFiller(candidate) ? candidate.trim() : '');
    if (!cleaned) continue;
    prompts++;
    if (isWeakPrompt(cleaned)) { if (!weak) weak = cleaned; } else if (!title) title = cleaned;
  }
  // The command the session was launched with names it better than a nudge;
  // /kresume names no task, and a stub (/clear) launches nothing.
  const command = launch && !STUB_COMMANDS.has(launch) && launch !== 'kresume' ? '/' + launch : '';
  return { title, weak, branch, command, prompts };
}

// Best name the prompts offer: a substantive prompt; else, for a session that
// only nudged ("continue"), its launch command or git branch; else the nudge
// itself (still better than a hash); else the branch; else ''. Same ladder as
// rename_sessions.py derive_name.
function promptName(scan) {
  if (scan.title) return scan.title;
  if (scan.weak) return scan.command || scan.branch || scan.weak;
  return scan.branch;
}

// Truncate to <=n, appending "…" when cut — identical to rename_sessions.py.
function truncateTitle(s, n = MAX_LABEL) {
  const label = (s || '').trim();
  if (label.length <= n) return label;
  return label.slice(0, n - 1).replace(/\s+$/, '') + '…';
}

// Readable base from the transcript, or '' when nothing descriptive exists.
function deriveBase(filePath) {
  const ai = readAiTitle(filePath);
  if (ai) return truncateTitle(ai);
  return truncateTitle(promptName(scanPrompts(filePath)));
}

/** Readable base title; the hash when the transcript offers nothing. */
function deriveReadableTitle(filePath, sessionId) {
  return deriveBase(filePath) || hashFallback(sessionId);
}

// The effective state of the LATEST custom-title record (what the picker shows),
// or null. { rawTitle, baseTitle, hasPrefix, finished }; baseTitle carries
// neither the live prefix nor the finished suffix.
function lastCustomTitle(filePath) {
  const lines = readSlice(filePath, true, TAIL_BYTES).split('\n');
  for (let i = lines.length - 1; i >= 0; i--) {
    if (lines[i].indexOf('"custom-title"') === -1) continue;
    const obj = parse(lines[i]);
    if (obj && obj.type === 'custom-title' && typeof obj.customTitle === 'string') {
      const raw = obj.customTitle;
      const has = raw.startsWith(LIVE_PREFIX);
      let base = has ? raw.slice(LIVE_PREFIX.length) : raw;
      const finished = base.endsWith(FINISHED_SUFFIX);
      if (finished) base = base.slice(0, -FINISHED_SUFFIX.length).trimEnd();
      return { rawTitle: raw, baseTitle: base, hasPrefix: has, finished };
    }
  }
  return null;
}

/**
 * The custom-title to append for a session entering `mode`, or null when the
 * current title is already right (or, in live mode, when writing now would
 * suppress the harness ai-title).
 *   mode 'live'     -> "⚡ <base>"
 *   mode 'finished' -> "<base> ✓ terminada"
 *   mode 'dead'     -> "<base>"
 * A human Ctrl+R name is kept as the base; only hash / wrapper-text titles are
 * replaced.
 */
function decideTitle(filePath, sessionId, mode) {
  const last = lastCustomTitle(filePath);
  if (mode === 'dead' && (!last || last.finished)) return null;   // nothing to unmark
  let base = last ? last.baseTitle : '';
  let scan = null;
  const getScan = () => (scan = scan || scanPrompts(filePath));
  // A stored branch name was only a stand-in: replace it once a real prompt exists.
  const standIn = () => !!base && base === getScan().branch && !!getScan().title;
  if (!base || isJunkTitle(base) || standIn()) {
    const ai = readAiTitle(filePath);
    if (ai) {
      base = truncateTitle(ai);
    } else {
      if (mode === 'live' && !last && getScan().prompts < DEFER_PROMPTS) return null;
      base = truncateTitle(promptName(getScan())) || hashFallback(sessionId);
    }
  }
  let want;
  if (mode === 'finished') want = base + FINISHED_SUFFIX;
  else if (mode === 'dead') want = base;
  else want = LIVE_PREFIX + base;
  if (last && last.rawTitle === want) return null;
  return want;
}

module.exports = {
  isHashTitle,
  isJunkTitle,
  isFiller,
  isWeakPrompt,
  hashFallback,
  readAiTitle,
  scanPrompts,
  cleanPrompt,
  truncateTitle,
  deriveReadableTitle,
  lastCustomTitle,
  decideTitle,
  MAX_LABEL,
  LIVE_PREFIX,
  FINISHED_SUFFIX,
  DEFER_PROMPTS,
};
