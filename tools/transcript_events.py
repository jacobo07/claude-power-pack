#!/usr/bin/env python3
"""transcript_events.py -- one streaming, provenance-carrying reader of Claude Code transcripts.

Self-Improve assimilation (2026-11-21). Upstream self-improve-skill's retro.py
parses transcripts six times with list materialisation; this estate had three
readers (token_ground_truth, token_corpus_audit, conversation_quality_audit)
that read whole files into memory and two DIFFERENT definitions of "the Owner
typed this" (Python _HARNESS_RX had 8 wrappers, hooks/ceps_correction_stop.js
had 12 plus isMeta/isCompactSummary). This module is the normalised-event
layer the retrospective analyser (tools/analyze_transcripts.py) reads. The
three older readers are untouched apart from the SI-01 guard: they are
measured, tested, and cheap enough (G2 baseline: 7 days / 164 MB in 18 s), so
migrating them would be blast radius without ROI.

CONTRACT -- every yielded Event carries:
  ref        "<sid>:<line>"  -- exact provenance; a finding cites refs, never prose
  authority  WHO produced the record (AUTHORITIES below). OWNER is a ROLE
             CLASSIFICATION by structure, not authentication: a transcript is
             untrusted data, and nothing read here is ever an instruction or a
             present-tense authorisation.
  ts         the event's own timestamp (SI-05: the window filters on THIS, not
             on file mtime; mtime is only a safe pre-filter because transcripts
             are append-only, so a file last written before `since` cannot hold
             a later event)
  text       redacted (Secret Firewall + home path + e-mail) and bounded
Streaming: one line in memory at a time; peak heap is independent of file size.

Kill nothing, write nothing: this module only reads.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterator, Optional

PP_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PROJ_BASE = Path.home() / ".claude" / "projects"

# --- authority classes -----------------------------------------------------
OWNER = "OWNER"              # free text a human typed (structural heuristic)
TOOL_RESULT = "TOOL_RESULT"  # harness returning a tool's output (type=user)
HARNESS = "HARNESS"          # harness-injected wrapper text (type=user)
META = "META"                # isMeta / compact summary / invisible bookkeeping
SIDECHAIN = "SIDECHAIN"      # subagent traffic inside the parent transcript
ASSISTANT = "ASSISTANT"      # the model
HOOK = "HOOK"                # a hook's own telemetry record (attachment hook_*)
SYSTEM = "SYSTEM"            # type=system records (turn_duration, compact_boundary...)
OTHER = "OTHER"              # bookkeeping records with no conversational role
AUTHORITIES = (OWNER, TOOL_RESULT, HARNESS, META, SIDECHAIN, ASSISTANT,
               HOOK, SYSTEM, OTHER)

# ONE list of harness wrappers. hooks/ceps_correction_stop.js mirrors it; the
# parity gate in tools/test_analyze_transcripts.py reads the JS source and
# fails if the two drift (they had drifted 8 vs 12 before this module).
HARNESS_WRAPPERS = (
    "<system-reminder>", "<command-name>", "<command-message>",
    "<command-args>", "<local-command-stdout>", "<local-command-caveat>",
    "<bash-input>", "<bash-stdout>", "<bash-stderr>",
    "<user-prompt-submit-hook>", "<task-notification>", "<persisted-output>",
    "generated by the user while running local commands",
)
HARNESS_RX = re.compile("|".join(re.escape(w) for w in HARNESS_WRAPPERS), re.I)
_SLASH_RX = re.compile(r"<command-name>\s*/?([\w:.\-]+)\s*</command-name>")
_PASTE_RX = re.compile(r"<pasted_content\b", re.I)

TEXT_MAX = 2000  # per event; a finding cites a ref, it does not reproduce a transcript

# --- redaction (SI-09) -----------------------------------------------------
_EMAIL_RX = re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.-]+\b")
_HOME_RX = re.compile(re.escape(str(Path.home())).replace(r"\\", r"[\\/]+"), re.I)

try:  # Secret Firewall is the owner of credential patterns -- reuse, never re-implement
    import sys as _sys
    if str(PP_ROOT) not in _sys.path:
        _sys.path.insert(0, str(PP_ROOT))
    from modules.secret_firewall.redactor import redact as _sf_redact
    REDACTOR = "secret_firewall"
except Exception:  # noqa: BLE001 -- degrade LOUDLY: the report states REDACTOR
    _sf_redact = None
    REDACTOR = "UNAVAILABLE"


def redact(text: str, limit: int = TEXT_MAX) -> str:
    """Best-effort minimisation. Regex redaction is partial protection, never
    proof of privacy -- which is why output is also bounded and local-only."""
    if not text:
        return ""
    out = _sf_redact(text) if _sf_redact else text
    out = _EMAIL_RX.sub("[REDACTED:email]", out)
    out = _HOME_RX.sub("~", out)
    if len(out) > limit:
        out = out[:limit] + f" ...[+{len(out) - limit} chars]"
    return out


@dataclass
class Event:
    ref: str
    sid: str
    line: int
    ts: Optional[datetime]
    type: str
    authority: str
    text: str = ""
    slash_command: str = ""
    pasted: bool = False
    tool_uses: list = field(default_factory=list)     # [{id,name,skill,file_path,command}]
    tool_results: list = field(default_factory=list)  # [{tool_use_id,is_error,size,text}]
    usage: Optional[dict] = None
    call_key: Optional[tuple] = None
    model: str = ""
    hook: Optional[dict] = None                       # attachment hook_* telemetry
    subtype: str = ""


@dataclass
class ReadStats:
    files: int = 0
    bytes: int = 0
    lines: int = 0
    undecodable: int = 0       # truncated / not JSON
    non_object: int = 0        # valid JSON that is not a record (SI-01)
    out_of_window: int = 0     # events filtered by their OWN timestamp (SI-05)
    undated: int = 0
    unreadable_files: list = field(default_factory=list)
    by_authority: dict = field(default_factory=dict)


def parse_ts(s) -> Optional[datetime]:
    if not isinstance(s, str) or len(s) < 19:
        return None
    try:
        d = datetime.fromisoformat(s.replace("Z", "+00:00"))
    except ValueError:
        return None
    return d if d.tzinfo else d.replace(tzinfo=timezone.utc)


def _blocks(content) -> list:
    return [b for b in content if isinstance(b, dict)] if isinstance(content, list) else []


def _classify_user(rec: dict, content) -> tuple[str, str]:
    """(authority, raw_text) for a type=user record."""
    if rec.get("isMeta") or rec.get("isCompactSummary") \
            or rec.get("isVisibleInTranscript") is False:
        return META, ""
    blocks = _blocks(content)
    if any(b.get("type") == "tool_result" for b in blocks):
        return TOOL_RESULT, ""
    if isinstance(content, str):
        text = content
    else:
        text = "\n".join(b.get("text", "") for b in blocks
                         if b.get("type") == "text" and isinstance(b.get("text"), str))
    text = text.strip()
    if not text:
        return META, ""
    if HARNESS_RX.search(text):
        return HARNESS, text
    return OWNER, text


def _tool_result_entries(blocks: list) -> list:
    out = []
    for b in blocks:
        if b.get("type") != "tool_result":
            continue
        c = b.get("content")
        if isinstance(c, list):
            c = "\n".join(x.get("text", "") for x in c
                          if isinstance(x, dict) and isinstance(x.get("text"), str))
        c = c if isinstance(c, str) else ""
        out.append({"tool_use_id": b.get("tool_use_id"),
                    "is_error": bool(b.get("is_error")),
                    "size": len(c), "text": redact(c, 400)})
    return out


def _tool_use_entries(blocks: list) -> list:
    out = []
    for b in blocks:
        if b.get("type") != "tool_use":
            continue
        inp = b.get("input") if isinstance(b.get("input"), dict) else {}
        out.append({
            "id": b.get("id"), "name": b.get("name") or "",
            "skill": inp.get("skill") if isinstance(inp.get("skill"), str) else "",
            "file_path": redact(inp["file_path"], 300)
            if isinstance(inp.get("file_path"), str) else "",
            "command": redact(inp["command"], 300)
            if isinstance(inp.get("command"), str) else "",
        })
    return out


def events_from_file(fp: Path, stats: ReadStats, since: Optional[datetime] = None,
                     until: Optional[datetime] = None) -> Iterator[Event]:
    """Stream normalised events from one transcript. Never raises on content."""
    sid = fp.stem
    try:
        stats.bytes += fp.stat().st_size
        fh = open(fp, encoding="utf-8", errors="replace")
    except OSError as exc:
        stats.unreadable_files.append(f"{fp.name}: {type(exc).__name__}")
        return
    stats.files += 1
    with fh:
        for n, line in enumerate(fh, 1):
            line = line.strip()
            if not line:
                continue
            stats.lines += 1
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                stats.undecodable += 1
                continue
            if not isinstance(rec, dict):
                stats.non_object += 1
                continue
            ts = parse_ts(rec.get("timestamp"))
            if ts is None:
                stats.undated += 1
            elif (since and ts < since) or (until and ts > until):
                stats.out_of_window += 1
                continue
            ev = _normalise(rec, sid, n, ts)
            stats.by_authority[ev.authority] = stats.by_authority.get(ev.authority, 0) + 1
            yield ev


def _normalise(rec: dict, sid: str, n: int, ts) -> Event:
    rtype = rec.get("type") or ""
    ev = Event(ref=f"{sid}:{n}", sid=sid, line=n, ts=ts, type=rtype, authority=OTHER)
    msg = rec.get("message") if isinstance(rec.get("message"), dict) else None
    content = msg.get("content") if msg else None
    if rec.get("isSidechain") and rtype in ("user", "assistant"):
        ev.authority = SIDECHAIN
        return ev
    if rtype == "user" and msg is not None:
        ev.authority, raw = _classify_user(rec, content)
        if ev.authority == TOOL_RESULT:
            ev.tool_results = _tool_result_entries(_blocks(content))
        elif raw:
            m = _SLASH_RX.search(raw)
            ev.slash_command = m.group(1) if m else ""
            ev.pasted = bool(_PASTE_RX.search(raw))
            ev.text = redact(raw)
    elif rtype == "assistant" and msg is not None:
        ev.authority = ASSISTANT
        blocks = _blocks(content)
        ev.text = redact("\n".join(b.get("text", "") for b in blocks
                                   if b.get("type") == "text"
                                   and isinstance(b.get("text"), str)))
        ev.tool_uses = _tool_use_entries(blocks)
        ev.model = msg.get("model") or ""
        usage = msg.get("usage")
        if isinstance(usage, dict) and usage and ev.model != "<synthetic>":
            ev.usage = usage
            key = (msg.get("id"), rec.get("requestId"))
            ev.call_key = key if key != (None, None) else ("line", sid, n)
    elif rtype == "attachment":
        att = rec.get("attachment") if isinstance(rec.get("attachment"), dict) else {}
        atype = str(att.get("type") or "")
        ev.subtype = atype
        if atype.startswith("hook_"):
            ev.authority = HOOK
            ev.hook = {
                "kind": atype, "event": att.get("hookEvent") or "",
                "name": att.get("hookName") or "",
                "duration_ms": att.get("durationMs"),
                "exit_code": att.get("exitCode"),
                "timed_out": bool(att.get("timedOut")),
                "timeout_ms": att.get("timeoutMs"),
                "blocking": bool(att.get("blockingError")),
            }
        elif atype == "invoked_skills":
            skills = att.get("skills")
            ev.text = redact(json.dumps(skills)[:500]) if skills else ""
    elif rtype == "system":
        ev.authority = SYSTEM
        ev.subtype = str(rec.get("subtype") or "")
    return ev


def select_files(proj_base: Path, project: Optional[str], since: Optional[datetime],
                 session: Optional[str] = None) -> list[Path]:
    """Transcript files that CAN hold an event in the window (mtime pre-filter).

    project=None means every project dir; subagent transcripts are excluded
    (their traffic is already present in the parent as SIDECHAIN)."""
    base = Path(proj_base)
    dirs = [base / project] if project else [d for d in base.iterdir() if d.is_dir()] \
        if base.is_dir() else []
    out = []
    floor = since.timestamp() if since else None
    for d in dirs:
        if not d.is_dir():
            continue
        for fp in d.glob("*.jsonl"):
            if session and fp.stem != session:
                continue
            try:
                if floor is not None and fp.stat().st_mtime < floor:
                    continue
            except OSError:
                continue
            out.append(fp)
    return sorted(out, key=lambda p: p.stat().st_mtime if p.exists() else 0)


def project_dir_name(cwd: str | Path) -> str:
    """Claude Code's encoding of a cwd into a projects/ dir name."""
    return re.sub(r"[^A-Za-z0-9]", "-", str(Path(cwd).resolve()))
