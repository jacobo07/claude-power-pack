#!/usr/bin/env python3
"""V-POP-*: the JS and python "which words did the Owner write" rules give the same answer.

hooks/prompt_origin.js exists because in-process dispatcher hooks (creative_grounding.js) cannot afford a python child
inside the 3 s UserPromptSubmit deadline. Two copies of one rule drift unless something compares them: this runs the
real JS CLI and modules.gsd_x.prompt_origin.owner_text over the same cases, both poles, and pins the prefix lists.
Run: python tools/test_prompt_origin_parity.py   (exit 0 = all pass)
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from modules.gsd_x import prompt_origin as po  # noqa: E402

JS = ROOT / "hooks" / "prompt_origin.js"
CASES = [
    "hazme una landing page para un estudio de yoga",                       # owner typed
    '  <pasted_content id="x">MISION: redisena la landing</pasted_content>',  # owner paste
    '"  <pasted_content id="y">quoted paste</pasted_content>',
    "<system-reminder>\n<tools-used-before-summary>Bash</tools-used-before-summary>\n</system-reminder>",
    "<system-reminder>x</system-reminder>\nmejora el dashboard",
    '<system-reminder kind="a">x</system-reminder>  <system-reminder>y</system-reminder>Another Claude session sent a '
    "message: hand-back",
    "Another Claude session sent a message: <agent-message>promo video</agent-message>",
    "This session is being continued from a previous conversation that ran out of context.",
    "<task-notification> <task-id>x</task-id> </task-notification>",
    "Base directory for this skill: C:\\skills\\x",
    "UserPromptSubmit hook additional context: tier",
    "Caveat: The messages below were generated by the user while running local commands.",
    "", "   ", "a" * 500,
]
RESULTS: list = []


def ok(name: str, cond: bool, detail: str = "") -> None:
    RESULTS.append((name, bool(cond)))
    print("  %s %-34s %s" % ("PASS" if cond else "FAIL", name, "" if cond else str(detail)[:600]))


def main() -> int:
    r = subprocess.run(["node", str(JS)], input=json.dumps(CASES), capture_output=True, text=True, encoding="utf-8",
                       timeout=60)
    js = json.loads(r.stdout) if r.stdout.strip() else None
    py = [po.owner_text(c) for c in CASES]
    diff = [(c[:60], a, b) for c, a, b in zip(CASES, py, js or [])] if js else []
    ok("V-POP-SAME-ANSWER", js is not None and len(js) == len(py) and all(a == b for _, a, b in diff),
       [d for d in diff if d[1] != d[2]] or r.stderr[-300:])
    ok("V-POP-BOTH-POLES", any(py) and any(c.strip() and not p for c, p in zip(CASES, py)), py)
    src = JS.read_text(encoding="utf-8")
    js_prefixes = [p for p in po.MACHINE_PREFIXES if "'%s'" % p in src]
    ok("V-POP-SAME-PREFIXES", js_prefixes == list(po.MACHINE_PREFIXES) and src.count("',\n") >= len(po.MACHINE_PREFIXES),
       set(po.MACHINE_PREFIXES) - set(js_prefixes))
    failed = [n for n, c in RESULTS if not c]
    print("V-POP: %d passed, %d failed" % (len(RESULTS) - len(failed), len(failed)))
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
