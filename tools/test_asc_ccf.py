FAILS = []


def check(n, c, d=""):
    print(("PASS " if c else "FAIL ") + n + (f" -- {d}" if d and not c else ""))
    if not c:
        FAILS.append(n)


def png(color: int) -> bytes:
    """A real, decodable 64x64 PNG (distinct per colour so identity is checkable)."""
    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    raw = b"".join(b"\x00" + bytes([color, 90, 40]) * 64 for _ in range(64))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 64, 64, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))


PNG_SPARK, PNG_THREAD = png(200), png(30)
CALLS: list = []
MODE = {"bytes": "good"}


class FakeAdapter:
    """Counting provider. Same return contract as GPTImage2Adapter (base64 ascii in bytes_)."""
    def generate(self, prompt, params=None):
        CALLS.append(prompt)
        if MODE["bytes"] == "garbage":
            payload = b"this is not an image at all" * 50
        elif MODE["bytes"] == "empty":
            payload = b""
        else:
            payload = PNG_THREAD if "loops back on itself" in prompt else PNG_SPARK
        return model_adapter.ImageArtifact(status="OK", provider="fake", model_id="fake-1",
                                           bytes_=base64.b64encode(payload), format="png",
                                           resolution="64x64", latency_ms=1.0, request_id="r1")


CONFIG = {"schema_version": "1.0", "theme": "modern", "accent": "#E85D3D", "headFont": "Poppins", "labels": [],
          "concepts": [
              {"id": "spark", "font": "Poppins Bold", "colours": ["#E85D3D"], "bg": "#FFFFFF",
               "wordmark": "Aperture", "avoid": [], "icon": "a four-point coral spark"},
              {"id": "thread", "font": "Poppins", "colours": ["#000000"], "bg": "#FFFFFF", "wordmark": "Aperture",
               "avoid": [], "icon": "a single continuous loop shape"}]}


def project(tmp: Path, name: str) -> str:
    p = tmp / name
    (p / ".ccf").mkdir(parents=True)
    (p / "config.json").write_text(json.dumps(CONFIG), encoding="utf-8")
    (p / "spec.json").write_text(json.dumps({"brand_name": "Aperture Coffee", "industry": "coffee",
                                              "audience": "pros", "values": ["craft"]}), encoding="utf-8")
    return str(p)


def run(argv) -> int:
    with contextlib.redirect_stdout(io.StringIO()):
        return cli.main(argv)


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


with tempfile.TemporaryDirectory() as t:
    t = Path(t)
    # isolate every side effect
    knowledge_feed.FEED_DIR = t / "feed"
    for n in ("CREATIVE_FAILURES_PATH", "PROVIDER_BENCHMARKS_PATH", "TRADEMARK_RISK_PATH"):
        setattr(knowledge_feed, n, knowledge_feed.FEED_DIR / getattr(knowledge_feed, n).name)
    cli.model_adapter.GPTImage2Adapter = FakeAdapter

    # sanity: the scanner really BLOCKs the 'thread' icon, and passes 'spark' (else D4 pole is vacuous)
    from modules.ccf import trademark_scanner as TS
    sp_v = TS.scan("spark", CONFIG["concepts"][0]["icon"])
    th_v = TS.scan("thread", CONFIG["concepts"][1]["icon"], ["loop", "ring"])
    print(f"INFO scanner: spark={sp_v['verdict']} thread={th_v['verdict']}")
    check("pole inputs: spark scans PASS", sp_v["verdict"] == "PASS", str(sp_v))
    check("pole inputs: thread scans BLOCK (so D4 is testable)", th_v["verdict"] == "BLOCK", str(th_v))

    # ------------------------------------------------------------------ main flow
    P = project(t, "main")
    CALLS.clear()
    rc = run(["generate", P])
    check("generate exits gate_blocked (3) because thread is BLOCKed", rc == 3, str(rc))
    called_blocked = [c for c in CALLS if "loops back" in c or "continuous loop" in c]
    check("D4: provider NOT invoked for the BLOCKed concept", called_blocked == [] and len(CALLS) == 1,
          f"calls={len(CALLS)}")
    check("D4 control: provider WAS invoked for the clean concept", any("coral spark" in c for c in CALLS))

    img = Path(P, ".ccf", "images", "spark.png")
    check("D1: generated bytes are kept on disk as a real PNG", img.is_file() and img.read_bytes()[:8] == b"\x89PNG\r\n\x1a\n")
    check("D1: the kept bytes are exactly what the provider returned", img.is_file() and img.read_bytes() == PNG_SPARK)
    check("D1 pole: no image file for the BLOCKed concept", not Path(P, ".ccf", "images", "thread.png").exists())

    man_p = Path(P, ".ccf", "manifest.json")
    man = json.loads(man_p.read_text()) if man_p.is_file() else {}
    ent = (man.get("artifacts") or man).get("spark") if man else None
    check("D2: manifest exists with path, sha256 and size for the kept artifact",
          bool(ent) and ent.get("sha256") == sha(PNG_SPARK) and ent.get("size") == len(PNG_SPARK) and ent.get("path"),
          str(ent))
    check("D2 pole: manifest does not list the BLOCKed concept", "thread" not in (man.get("artifacts") or man))

    check("select spark exits 0", run(["select", P, "--concept", "spark", "--by", "gate"]) == 0)
    rc = run(["package", P])
    check("package SEALED (exit 0) with real evidence", rc == 0, str(rc))
    kit = Path(P, "brandkit.html")
    html = kit.read_text() if kit.is_file() else ""
    m = re.search(r"data:image/png;base64,([A-Za-z0-9+/=]+)", html)
    check("D3: published kit embeds the generated logo",
          bool(m) and sha(base64.b64decode(m.group(1))) == sha(PNG_SPARK), "no embedded image or hash differs")
    rel = json.loads(Path(P, ".ccf", "releases", "1.json").read_text()) if Path(P, ".ccf/releases/1.json").is_file() else {}
    check("D3/D5: sealed release records the verified artifact hash",
          (rel.get("artifact_hashes") or {}).get("spark") == sha(PNG_SPARK), str(rel.get("artifact_hashes")))

    # ------------------------------------------------------------------ D5 poles: no positive evidence -> never SEALED
    # (a) image deleted after generation
    P2 = project(t, "deleted")
    run(["generate", P2, "--only", "spark"])
    run(["select", P2, "--concept", "spark", "--by", "gate"])
    for f in Path(P2, ".ccf", "images").glob("*"):
        f.unlink()
    rc2 = run(["package", P2])
    check("D5: package is BLOCKED when the kept artifact is gone", rc2 == 3, str(rc2))
    check("D5: no release version written without evidence", not any(Path(P2, ".ccf", "releases").glob("*.json"))
          if Path(P2, ".ccf", "releases").exists() else True)

    # (b) file replaced by different bytes (hash mismatch)
    P3 = project(t, "tampered")
    run(["generate", P3, "--only", "spark"])
    run(["select", P3, "--concept", "spark", "--by", "gate"])
    for f in Path(P3, ".ccf", "images").glob("*"):
        f.write_bytes(PNG_THREAD)
    check("D5: package is BLOCKED when the artifact no longer matches its manifest hash",
          run(["package", P3]) == 3)

    # (c) forged record: status OK in image_artifacts.json with no file and no manifest
    P4 = project(t, "forged")
    run(["generate", P4, "--only", "spark"])
    run(["select", P4, "--concept", "spark", "--by", "gate"])
    for f in Path(P4, ".ccf", "images").glob("*"):
        f.unlink()
    Path(P4, ".ccf", "manifest.json").unlink(missing_ok=True)
    rec = json.loads(Path(P4, ".ccf", "image_artifacts.json").read_text())
    rec["spark"]["status"] = "OK"
    Path(P4, ".ccf", "image_artifacts.json").write_text(json.dumps(rec))
    check("D5: a forged status=OK record with no artifact cannot seal", run(["package", P4]) == 3)

    # (d) provider claims OK but returns garbage / empty bytes: generation must fail, not seal
    for kind in ("garbage", "empty"):
        MODE["bytes"] = kind
        P5 = project(t, f"bad-{kind}")
        rcg = run(["generate", P5, "--only", "spark"])
        check(f"D1/D5: provider OK with {kind} bytes is a provider error (exit 2), not a success", rcg == 2, str(rcg))
        check(f"D1: no file written for {kind} bytes", not any(Path(P5, ".ccf", "images").glob("*"))
              if Path(P5, ".ccf", "images").exists() else True)
        run(["select", P5, "--concept", "spark", "--by", "gate"])
        check(f"D5: package cannot seal over {kind} bytes", run(["package", P5]) == 3)
    MODE["bytes"] = "good"

    # D5 control already shown by the main flow (SEALED with evidence).

print(f"\n{'V-ASC-CCF PASS' if not FAILS else 'V-ASC-CCF FAIL: ' + ', '.join(FAILS)}")
sys.exit(1 if FAILS else 0)
