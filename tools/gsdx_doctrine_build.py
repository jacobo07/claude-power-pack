#!/usr/bin/env python3
"""Build doctrine/ENFORCEMENT.md and merge the 41 enforcer dispositions into l1/review.json (then rerun the classifier)."""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gsdx_doctrine_gate as G  # noqa: E402

RULES = {
    "commit": "Every commit is a micro-commit: one logical step, pathspec-scoped, and no recent commit may touch more than "
              f"{G.MAX_FILES_PER_COMMIT} files; a sweep commit is a defect to split, not to excuse.",
    "authority": "Owner approval and scope are asked once and recorded in the master plan; a work unit stops at its hard ceiling "
                 "and every packet closes with a HANDOFF NOTE instead of ending on a question.",
    "delegation": "Work is delegated only through a compiled packet that names its done_gate and work_tree up front; "
                  "a worker never self-assigns scope beyond its packet and continues from the packet's progress file.",
    "economics": "Every spend is priced before it starts: a packet's closeout section must state a numeric tool-call budget, "
                 "and an unknown or null cost is treated as unpriced, never as free.",
    "knowledge": "Reality and prior knowledge are read before work (UKDL, CLAE rules, sections ledger); each failure or "
                 "reconstruction lesson lands in those corpora rather than only in a transcript.",
}


def main() -> int:
    out = ["# U-DOCTRINE enforcement map", "",
           "Generated by tools/gsdx_doctrine_build.py. Each cluster is enforced by `tools/gsdx_doctrine_gate.py --cluster <name>`",
           "(section intact AND live check over this tree). Rows are satisfied only while that gate exits 0.", ""]
    rv_path = ROOT / "vault/specs/gsdx-factory/l1/review.json"
    rv = json.loads(rv_path.read_text(encoding="utf-8-sig"))
    py = "C:\\Users\\User\\AppData\\Local\\Programs\\Python\\Python312\\python.exe"
    for c, ids in G.CLUSTERS.items():
        out += [f"## CLUSTER {c}", f"RULE: {RULES[c]}", "ENFORCER: tools/gsdx_doctrine_gate.py", "ROWS:"]
        out += [f"- S-{i}" for i in ids] + [""]
        for i in ids:
            rv["S-" + i] = {
                "claimed": "REUSE_EXISTING", "reason": f"DOCTRINE-ENFORCER cluster {c}: gate enforces the rule",
                "evidence": [{"kind": "cmd_rc0", "cmd": [py, "tools/gsdx_doctrine_gate.py", "--cluster", c],
                              "cwd": str(ROOT), "marker": f"DOCTRINE-GATE OK {c}", "timeout": 120}]}
    G.DOC.parent.mkdir(parents=True, exist_ok=True)
    G.DOC.write_text("\n".join(out), encoding="utf-8")
    rv_path.write_text(json.dumps(rv, indent=1), encoding="utf-8")
    p = subprocess.run([sys.executable, "-I", str(ROOT / "tools/gsdx_l1_classify.py")], capture_output=True, text=True, timeout=300)
    print(p.stdout.strip(), p.stderr.strip()[-300:])
    return p.returncode


if __name__ == "__main__":
    sys.exit(main())
