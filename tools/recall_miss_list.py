"""Render the recall baseline's misses and false positives as markdown (deterministic, no model).

Usage: python tools/recall_miss_list.py <report.json> <queries.jsonl> <out.md>
"""
import json
import sys
from collections import Counter

report_path, queries_path, out_path = sys.argv[1:4]
r = json.load(open(report_path, encoding="utf-8"))
q = {}
for ln in open(queries_path, encoding="utf-8"):
    if ln.strip():
        d = json.loads(ln)
        q[d["id"]] = d


def base(p):
    return str(p).replace("/", "\\").split("\\")[-1]


m = r["metrics"]
lines = [
    "# Recall baseline: misses and false positives",
    "",
    f"Source: `vault/evals/recall/report-baseline.json` (label `{r['label']}`, measured {r['measured_at']}, "
    f"{r['index_files']} indexed files). Generated by `tools/recall_miss_list.py` from that report; "
    "no model judgement.",
    "",
    f"- recall@5 {m['recall_at_5']} over {m['positives_scored']} positives; MRR {m['mrr']}",
    f"- by language: " + ", ".join(f"{k} {v['recall_at_5']} (n={v['n']})" for k, v in m["by_lang"].items()),
    f"- negatives: {m['negatives_scored']}, false-positive rate {m['negative_false_positive_rate']}",
    f"- foreign-memory hit share {m['foreign_memory_hit_share']}; stale hit share {m['stale_hit_share']}",
    f"- miss classes: " + ", ".join(f"{k} {v}" for k, v in m["miss_classes"].items()),
    "",
]
misses = [x for x in r["rows"] if not x["negative"] and x["status"] != "HIT"]
fps = [x for x in r["rows"] if x["negative"] and x["status"] == "FALSE_POSITIVE"]
by_class = Counter(x.get("miss_class") for x in misses)
by_domain = Counter(x["domain"] for x in misses)
lines += [f"## Misses ({len(misses)})", "",
          "By domain: " + ", ".join(f"{k} {v}" for k, v in by_domain.most_common()), ""]
for cls, _n in by_class.most_common():
    lines += [f"### {cls} ({_n})", "", "| id | lang | domain | query | expected | top-3 returned |",
              "|---|---|---|---|---|---|"]
    for x in misses:
        if x.get("miss_class") != cls:
            continue
        d = q.get(x["id"], {})
        exp = d.get("expect") or []
        exp = exp if isinstance(exp, list) else [exp]
        lines.append("| {} | {} | {} | {} | {} | {} |".format(
            x["id"], x["lang"], x["domain"], str(d.get("q", "")).replace("|", "/"),
            ", ".join(f"`{base(e)}`" for e in exp),
            ", ".join(f"`{base(h['path'])}`" for h in x["hits"][:3]) or "(none)"))
    lines.append("")
lines += [f"## False positives ({len(fps)} of {m['negatives_scored']} negatives)", "",
          "| id | lang | query | returned |", "|---|---|---|---|"]
for x in fps:
    d = q.get(x["id"], {})
    lines.append("| {} | {} | {} | {} |".format(
        x["id"], x["lang"], str(d.get("q", "")).replace("|", "/"),
        ", ".join(f"`{base(h['path'])}`" for h in x["hits"][:5])))
lines.append("")
open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print(f"misses={len(misses)} fps={len(fps)} classes={dict(by_class)} -> {out_path}")
